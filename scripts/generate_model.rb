# frozen_string_literal: true

# Writes lib/amath/model/nodes.rb, the plain LML classes of the AsciiMath
# model, from the static capture shapes of the normalized grammars of both
# dialects (grammars/asciimath.normalized-rules.json and
# grammars/pma.normalized-rules.json, written by
# scripts/generate_grammar.rb), and model/asciimath.lml.json, the LML
# export of every model class.
#
# The two dialects share one model: a capture name means the same class in
# both grammars, with the union of the keys either grammar gives it, so a
# pma measured value is the same Uncertainty (and Unit) class as a dialect
# L one. The two must agree on each shared capture's kind. Every registry
# binding's target must be the type its leaf capture gets here.
#
# Usage:
#   bundle exec ruby scripts/generate_model.rb            write both files
#   bundle exec ruby scripts/generate_model.rb --check    exit 1 if stale
#
# After normalization every capture holds one kind, so the mapping is
# mechanical and needs no union, cast hook or walker:
#
#   capture of kind hash  -> class <Capture>, one attribute per key
#   capture of kind list  -> class <Capture>Item for the elements; the
#                            attribute is a collection of it
#   capture of kind text  -> :string attribute
#   catalog capture       -> Amath::Model::MathSymbol (a hash whose only
#                            key is `spelling`, rule N9); a class with
#                            `spelling` beside other keys gets MathSymbol's
#                            derived value and kind
#
# An attribute has the same name and type wherever it occurs, because its
# type is the type of the capture it names. The `root` capture of the entry
# rule is the class Expression; Amath::Model::Document (lib/amath/model.rb)
# holds it.

require "digest"
require "json"
require_relative "amath_shapes"
require_relative "registry"

ROOT = File.expand_path("..", __dir__)
RULES = File.join(ROOT, "grammars/asciimath.normalized-rules.json")
PMA_RULES = File.join(ROOT, "grammars/pma.normalized-rules.json")
OUT = File.join(ROOT, "lib/amath/model/nodes.rb")
LML_OUT = File.join(ROOT, "model/asciimath.lml.json")
TREE = "root"
NS = "Amath::Model"
SYMBOL = "MathSymbol"
RESERVED = { "root" => "Expression", "symbol" => "SymbolNode" }.freeze

check = ARGV.delete("--check")
abort "usage: ruby scripts/generate_model.rb [--check]" unless ARGV.empty?

solve = lambda do |path|
  AmathShapes.new(JSON.parse(File.read(path, encoding: "UTF-8")).fetch("rules"), normalized: true).solve
end
caps = solve.call(RULES)
abort "the normalized grammar has no #{TREE} capture" unless caps.key?(TREE)
pma_caps = solve.call(PMA_RULES)
abort "the pma grammar must not capture #{TREE}" if pma_caps.key?(TREE)
pma_caps.each do |name, shape|
  if caps.key?(name)
    a = caps[name].solid
    b = shape.solid
    abort "capture #{name} is #{a.to_a.join('|')} in dialect L and #{b.to_a.join('|')} in pma" unless a == b || a.empty? || b.empty?
    caps[name] |= shape
  else
    caps[name] = shape
  end
end

kind = lambda do |name|
  solid = caps.fetch(name).solid
  abort "capture #{name} holds #{solid.to_a.join('|')}; normalize the grammar first" unless solid.size <= 1
  abort "capture #{name} only ever holds nil" if solid.empty? && caps.fetch(name).kinds.include?(:nil)
  solid.first || :string
end
catalog = ->(name) { kind.call(name) == :hash && caps[name].hash_keys.to_a == ["spelling"] }
camel = ->(n) { RESERVED[n] || n.split("_").map { |w| w[0].upcase + w[1..] }.join }

classes = {} # class name => [capture, attribute keys]
caps.keys.sort.each do |name|
  next if catalog.call(name)

  case kind.call(name)
  when :hash then classes[camel.call(name)] = [name, caps[name].hash_keys.to_a.sort]
  when :array then classes["#{camel.call(name)}Item"] = [name, caps[name].array_keys.to_a.sort]
  end
end

type_of = lambda do |key|
  return %("#{NS}::#{SYMBOL}") if catalog.call(key)

  case kind.call(key)
  when :hash then %("#{NS}::#{camel.call(key)}")
  when :array then %("#{NS}::#{camel.call(key)}Item", collection: true)
  else ":string"
  end
end

registry = Registry.load
registry.fetch("bindings").each do |name, binding|
  binding.each do |leaf, target|
    next unless caps.key?(leaf)

    type = type_of.call(leaf).delete('"').split(",").first
    want = target == "string" ? ":string" : target
    abort "binding #{name}: leaf #{leaf} is #{type}, the registry says #{target}" unless type == want
  end
end

out = +<<~RUBY
  # frozen_string_literal: true

  # GENERATED by scripts/generate_model.rb from the normalized grammar's
  # capture shapes -- do not edit. #{classes.size} classes; MathSymbol and
  # Document are in lib/amath/model.rb.
  module Amath
    module Model
RUBY
classes.sort.each_with_index do |(cname, (capture, keys)), i|
  what = cname.end_with?("Item") && kind.call(capture) == :array ? "An element of capture" : "Capture"
  out << "\n" unless i.zero?
  out << "    # #{what} +#{capture}+.\n    class #{cname} < Lutaml::Model::Serializable\n"
  keys.each { |k| out << "      attribute :#{k}, #{type_of.call(k)}\n" }
  if keys.include?("spelling")
    # A catalog spelling beside other keys: resolved as MathSymbol's.
    abort "#{cname} has both spelling and #{(keys & %w[value kind]).join(', ')}" if keys.intersect?(%w[value kind])
    out << "      attribute :value, :string, method: :symbol_value\n"
    out << "      attribute :kind, :string, method: :symbol_kind\n"
    out << "      include Spelled\n"
  end
  out << "    end\n"
end
out << "  end\nend\n"

# The LML documents of every model class, generated and hand-written, in
# class-name order. Needs the classes loaded, so it runs on the written
# (or, with --check, the committed) nodes.rb.
def lml_export
  $LOAD_PATH.unshift(File.join(ROOT, "lib"))
  require "amath"
  require "amath/model"
  docs = Amath::Model.classes.map do |klass|
    exported = Lutaml::Model::Lml.export(klass)
    Lutaml::Model::Lml.verify(Lutaml::Model::Lml::Document.from_hash(exported.to_h))
    exported.to_h
  end
  "#{JSON.pretty_generate('format' => 'amath-lml/1', 'models' => docs)}\n"
end

relative = ->(path) { path.delete_prefix("#{ROOT}/") }
if check
  stale = File.exist?(OUT) && File.read(OUT) == out ? [] : [OUT]
  stale << LML_OUT unless stale.empty? || (File.exist?(LML_OUT) && File.read(LML_OUT) == lml_export)
  if stale.empty?
    puts "#{relative.(OUT)}, #{relative.(LML_OUT)} up to date"
  else
    warn "stale: #{stale.map(&relative).join(', ')}; run bundle exec ruby scripts/generate_model.rb"
    exit 1
  end
else
  File.write(OUT, out)
  puts "wrote #{relative.(OUT)}: #{classes.size} generated classes"
  lml = lml_export
  File.write(LML_OUT, lml)
  puts "wrote #{relative.(LML_OUT)}: #{JSON.parse(lml)['models'].size} models sha256:#{Digest::SHA256.hexdigest(lml)}"
end
